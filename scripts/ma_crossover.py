"""Backtest a 50/200-day moving-average crossover against buy-and-hold.

Runs offline on the prices in dashboard/data.json (SPY + 16 large US stocks,
2019 onwards, adjusted for dividends and splits) and writes
reports/ma_crossover.md plus a chart in reports/.

    python scripts/ma_crossover.py

It uses your metric functions from src/wikiquant/metrics.py (the Week 1
exercise), so finish those first: until then it stops with a reminder.
The explanation of every step is in docs/ma-crossover.md.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

from wikiquant import metrics as M
from wikiquant.backtest import count_trades, run_backtest
from wikiquant.dataset import load_dataset
from wikiquant.strategies import buy_and_hold, sma_crossover

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "reports" / "ma_crossover.md"
CHART = ROOT / "reports" / "ma_crossover_spy.png"

FAST, SLOW = 50, 200
COST_BPS = 10           # per unit of turnover; SPY really costs ~1-2 bps, single stocks a few
GRID_FAST = [10, 20, 50, 100]
GRID_SLOW = [100, 150, 200, 250]
WARMUP = max(GRID_SLOW)  # every test starts on the same day, after the longest average exists


def check_metrics_done() -> None:
    try:
        M.simple_returns(pd.Series([1.0, 2.0]))
        M.max_drawdown(pd.Series([0.1, -0.1]))
    except NotImplementedError:
        sys.exit("Finish the Week 1 exercise in src/wikiquant/metrics.py first "
                 "(pytest tests/test_metrics.py), then run this again.")


def from_start(positions, start):
    """Zero positions before the common start date, so both strategies enter on the same day."""
    p = positions.copy()
    p.loc[p.index < start] = 0.0
    return p


def summary(bt: pd.DataFrame, positions: pd.Series | None = None) -> dict:
    r = bt["net_ret"]
    return {
        "CAGR": M.annualised_return(r),
        "Volatility": M.annualised_volatility(r),
        "Sharpe": M.sharpe_ratio(r),
        "Max drawdown": M.max_drawdown(r),
        "Growth of $1": bt["equity"].iloc[-1],
        "Time invested": (bt["position"] > 0).mean(),
        "Trades": count_trades(positions) if positions is not None else None,
        "Costs paid / yr": bt["cost"].sum() / (len(bt) / M.TRADING_DAYS),
    }


def pct(x, d=1):
    return "" if x is None or pd.isna(x) else f"{x * 100:+.{d}f}%"


def fmt_row(name, s):
    return (f"| {name} | {pct(s['CAGR'])} | {s['Volatility'] * 100:.1f}% | {s['Sharpe']:.2f} | "
            f"{pct(s['Max drawdown'])} | {s['Growth of $1']:.2f} | {s['Time invested'] * 100:.0f}% | "
            f"{s['Trades'] if s['Trades'] is not None else ''} | {s['Costs paid / yr'] * 100:.2f}% |")


HEADER = ("| | CAGR | Volatility | Sharpe | Max drawdown | Growth of $1 | Time invested | Trades | Costs / yr |\n"
          "| --- | --- | --- | --- | --- | --- | --- | --- | --- |")


def make_chart(bt_s, bt_b, pos, start):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 6.5), sharex=True,
                                   gridspec_kw={"height_ratios": [3, 1.2]})
    ax1.plot(bt_b.index, bt_b["equity"], color="#2a6fdb", lw=1.6, label="Buy and hold")
    ax1.plot(bt_s.index, bt_s["equity"], color="#e07b00", lw=1.6, label=f"{FAST}/{SLOW} crossover")
    out = pos.loc[start:] == 0
    ax1.fill_between(out.index, 0, 1, where=out, transform=ax1.get_xaxis_transform(),
                     color="#e07b00", alpha=0.08, lw=0, label="Crossover in cash")
    ax1.set_ylabel("Growth of $1")
    ax1.legend(loc="upper left", frameon=False)
    ax1.set_title("SPY: moving-average crossover vs buy and hold (after 10 bps costs)", loc="left")
    for bt, c in ((bt_b, "#2a6fdb"), (bt_s, "#e07b00")):
        eq = bt["equity"]
        ax2.plot(eq.index, (eq / eq.cummax() - 1) * 100, color=c, lw=1.2)
    ax2.set_ylabel("Drawdown %")
    for a in (ax1, ax2):
        a.spines[["top", "right"]].set_visible(False)
        a.grid(alpha=0.25)
    fig.tight_layout()
    fig.savefig(CHART, dpi=130)
    plt.close(fig)


def main() -> None:
    check_metrics_done()
    ds = load_dataset()
    spy = ds.bench.dropna()
    start = spy.index[WARMUP]
    lines = []
    w = lines.append

    # 1. Headline: SPY
    pos_s = from_start(sma_crossover(spy, FAST, SLOW), start)
    pos_b = from_start(buy_and_hold(spy), start)
    bt_s = run_backtest(spy, pos_s, COST_BPS).loc[start:]
    bt_b = run_backtest(spy, pos_b, COST_BPS).loc[start:]
    s_s, s_b = summary(bt_s, pos_s.loc[start:]), summary(bt_b, pos_b.loc[start:])
    make_chart(bt_s, bt_b, pos_s, start)

    w("# Moving-average crossover vs buy and hold\n")
    w(f"_Generated by `scripts/ma_crossover.py` from data built {ds.built}. "
      f"Test period {start:%d %b %Y} to {spy.index[-1]:%d %b %Y} "
      f"({len(bt_s) / 252:.1f} years). Costs {COST_BPS} bps per unit traded. "
      "How it works and how to read it: [`docs/ma-crossover.md`](../docs/ma-crossover.md)._\n")
    w(f"**Rule:** hold SPY while its {FAST}-day average price is above its {SLOW}-day average, "
      "otherwise hold cash (earning 0%). Signal at today's close, trade at today's close, "
      "earn from tomorrow.\n")
    w("## 1. SPY\n")
    w(HEADER)
    w(fmt_row("Buy and hold", s_b))
    w(fmt_row(f"{FAST}/{SLOW} crossover", s_s))
    w("")
    w(f"![SPY equity curves]({CHART.name})\n")

    # 2. Year by year
    w("### Year by year\n")
    w("| Year | Buy and hold | Crossover | Difference | Days in cash |\n| --- | --- | --- | --- | --- |")
    for year, g in bt_s.groupby(bt_s.index.year):
        b = bt_b.loc[g.index, "net_ret"]
        rs, rb = (1 + g["net_ret"]).prod() - 1, (1 + b).prod() - 1
        w(f"| {year} | {pct(rb)} | {pct(rs)} | {pct(rs - rb)} | {(g['position'] == 0).sum()} |")
    w("")

    # 3. Costs and timing
    w("## 2. How fragile is it? Costs and timing\n")
    w("| Setting | Crossover CAGR | Crossover Sharpe | Buy-and-hold CAGR |\n| --- | --- | --- | --- |")
    for bps in (0, 5, 10, 25, 50):
        a = summary(run_backtest(spy, pos_s, bps).loc[start:])
        b = summary(run_backtest(spy, pos_b, bps).loc[start:])
        w(f"| {bps} bps, trade same close | {pct(a['CAGR'])} | {a['Sharpe']:.2f} | {pct(b['CAGR'])} |")
    a = summary(run_backtest(spy, pos_s, COST_BPS, lag=2).loc[start:])
    w(f"| {COST_BPS} bps, trade one day later | {pct(a['CAGR'])} | {a['Sharpe']:.2f} | {pct(s_b['CAGR'])} |")
    w("")

    # 4. Parameter grid
    w("## 3. Did we just pick lucky numbers? Every fast/slow pair\n")
    w(f"Sharpe ratio after costs for each pair (buy and hold: **{s_b['Sharpe']:.2f}**). "
      "Same test period for every cell.\n")
    w("| fast \\ slow | " + " | ".join(map(str, GRID_SLOW)) + " |")
    w("| --- |" + " --- |" * len(GRID_SLOW))
    for f in GRID_FAST:
        cells = []
        for s in GRID_SLOW:
            if f >= s:
                cells.append("")
                continue
            p = from_start(sma_crossover(spy, f, s), start)
            cells.append(f"{summary(run_backtest(spy, p, COST_BPS).loc[start:])['Sharpe']:.2f}")
        w(f"| {f} | " + " | ".join(cells) + " |")
    w("")

    # 5. Single stocks
    w("## 4. Same rule on 16 single stocks\n")
    w("Each stock tested on its own, same period and costs. These 16 are famous *today*, "
      "which flatters buy and hold (survivorship bias), so treat this as a stress test of the "
      "rule, not a forecast.\n")
    w("| Stock | B&H CAGR | Crossover CAGR | B&H Sharpe | Crossover Sharpe | B&H max DD | Crossover max DD | Trades |\n"
      "| --- | --- | --- | --- | --- | --- | --- | --- |")
    better_sharpe = better_dd = n = 0
    for t in ds.prices.columns:
        px = ds.prices[t].dropna()
        if px.index[0] > start:
            continue
        ps = from_start(sma_crossover(px, FAST, SLOW), start)
        pb = from_start(buy_and_hold(px), start)
        a = summary(run_backtest(px, ps, COST_BPS).loc[start:], ps.loc[start:])
        b = summary(run_backtest(px, pb, COST_BPS).loc[start:])
        n += 1
        better_sharpe += a["Sharpe"] > b["Sharpe"]
        better_dd += a["Max drawdown"] > b["Max drawdown"]
        w(f"| {t} | {pct(b['CAGR'])} | {pct(a['CAGR'])} | {b['Sharpe']:.2f} | {a['Sharpe']:.2f} | "
          f"{pct(b['Max drawdown'], 0)} | {pct(a['Max drawdown'], 0)} | {a['Trades']} |")
    w("")
    w(f"The crossover had a higher Sharpe on **{better_sharpe} of {n}** stocks and a smaller "
      f"worst drawdown on **{better_dd} of {n}**.\n")

    REPORT.write_text("\n".join(lines))
    print(f"Wrote {REPORT.relative_to(ROOT)} and {CHART.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
