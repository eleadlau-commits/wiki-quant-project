"""Run the same tests on every attention source and write a comparison report.

Works offline from dashboard/data.json (refreshed daily by the GitHub Action):

    python scripts/compare_sources.py                  # -> reports/attention_comparison.md
    python scripts/compare_sources.py --threshold 4

For each source it reports:
1. Event study: after a spike, did the stock beat the S&P 500 over the next
   20 trading days, compared with a normal 20 days? With a t-stat.
2. Already priced in?: the move on the day you could first trade.
3. Stability: the same number in the first and second half of the period.
4. Weekly Buzz 4 strategy vs equal weight, and how much one company carries it.
5. Overlap: do the sources spike on the same news?
"""

from __future__ import annotations

import argparse
import sys
from itertools import combinations
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from wikiquant import analysis as A  # noqa: E402
from wikiquant import metrics  # noqa: E402
from wikiquant.dataset import load_dataset  # noqa: E402


def pct(x, d=1):
    return "–" if x is None or not np.isfinite(x) else f"{x * 100:+.{d}f}%"


def num(x, d=1):
    return "–" if x is None or not np.isfinite(x) else f"{x:.{d}f}"


def share(x):
    return "–" if x is None or not np.isfinite(x) else f"{x * 100:.0f}%"


def try_metric(fn, r):
    """Use your metrics.py if you've written it; otherwise leave a gap."""
    try:
        return fn(r)
    except NotImplementedError:
        return None


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(ROOT / "dashboard" / "data.json"))
    ap.add_argument("--threshold", type=float, default=3.0)
    ap.add_argument("--out", default=str(ROOT / "reports" / "attention_comparison.md"))
    args = ap.parse_args()

    ds = load_dataset(args.data)
    base = A.baseline_excess(ds.prices, ds.bench).mean()
    results = {}
    for sid, meta in ds.sources.items():
        results[sid] = A.run_source(sid, ds.attention[sid], ds.prices, ds.bench,
                                    smooth=meta.get("smooth", 1), threshold=args.threshold)

    L = [f"# Attention sources compared",
         "",
         f"Data built {ds.built}, prices {ds.prices.index[0].date()} to {ds.prices.index[-1].date()}, "
         f"{ds.prices.shape[1]} stocks, spike = {args.threshold:g}x usual attention. "
         "Generated by `scripts/compare_sources.py`; every source goes through identical code.",
         "",
         "## 1. After a spike, does the stock beat the S&P 500?",
         "",
         f"Return minus the S&P 500 over the {A.HOLD} trading days after the first day you could trade. "
         f"A normal {A.HOLD}-day stretch for these stocks averages **{pct(base)}**. "
         "|t| under about 2 means luck could easily explain it.",
         "",
         "| Source | Spikes | Next 20 days vs S&P | Beat S&P | t-stat | Day-0 move (already priced in) | 1st half | 2nd half |",
         "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for sid, res in results.items():
        ev = res.events
        s = A.summarise(ev["excess"])
        mid = ds.prices.index[len(ds.prices) // 2]
        h1 = A.summarise(ev.loc[ev["entry_date"] < mid, "excess"])
        h2 = A.summarise(ev.loc[ev["entry_date"] >= mid, "excess"])
        react = A.summarise(ev["reaction"])
        L.append(f"| {ds.sources[sid]['label']} | {s['n']} | {pct(s['mean'])} | {share(s['hit'])} | {num(s['t'])} "
                 f"| {pct(react['mean'], 2)} | {pct(h1['mean'])} (t {num(h1['t'])}) | {pct(h2['mean'])} (t {num(h2['t'])}) |")

    L += ["", "### Per company", ""]
    for sid, res in results.items():
        per = res.events.groupby("ticker")["excess"].apply(A.summarise).unstack()
        per = per.reindex(ds.prices.columns)
        L += [f"**{ds.sources[sid]['label']}**", "",
              "| Ticker | Spikes | Next 20 days vs S&P | t-stat |", "| --- | ---: | ---: | ---: |"]
        for t, row in per.sort_values("mean", ascending=False).iterrows():
            n = 0 if pd.isna(row["n"]) else int(row["n"])
            L.append(f"| {t} | {n} | {pct(row['mean'])} | {num(row['t'])} |")
        L.append("")

    L += ["## 2. Weekly strategy: Buzz 4 vs equal weight", "",
          f"Every Monday hold the {A.TOP_K} stocks with the most abnormal attention last week (Buzz) "
          f"or the least (Quiet). Edge = average yearly gap vs holding all stocks equally.",
          "",
          "| Source | Buzz − equal weight, per year | t-stat | Buzz − Quiet, per year | Biggest single contributor | Edge without it | Buzz CAGR | Buzz Sharpe | Buzz worst drop |",
          "| --- | ---: | ---: | ---: | --- | ---: | ---: | ---: | ---: |"]
    for sid, res in results.items():
        if res.daily.empty:
            L.append(f"| {ds.sources[sid]['label']} | not enough data | | | | | | | |")
            continue
        e = A.annual_edge(res.daily)
        bq = A.annual_edge(res.daily, "buzz", "quiet")
        top = res.loo.iloc[0]
        r = res.daily["buzz"].dropna()
        cagr = try_metric(metrics.annualised_return, r)
        sharpe = try_metric(metrics.sharpe_ratio, r)
        mdd = try_metric(metrics.max_drawdown, r)
        L.append(f"| {ds.sources[sid]['label']} | {pct(e['edge'])} | {num(e['t'])} | {pct(bq['edge'])} "
                 f"| {top['ticker']} | {pct(top['edge_without'])} | {pct(cagr)} | {num(sharpe, 2)} | {pct(mdd, 0)} |")
    L += ["", "_CAGR, Sharpe and worst drop come from your `metrics.py`; they show – until you write those functions._", ""]

    if len(results) > 1:
        L += ["## 3. Do the sources see the same thing?", "",
              "| Pair | Correlation of daily attention ratios | Share of A's spikes with a B spike within 2 days | Share of B's with an A spike |",
              "| --- | ---: | ---: | ---: |"]
        for a, b in combinations(results, 2):
            corr = A.ratio_correlation(ds.attention[a], ds.sources[a].get("smooth", 1),
                                       ds.attention[b], ds.sources[b].get("smooth", 1))
            L.append(f"| A = {ds.sources[a]['label']}, B = {ds.sources[b]['label']} | {num(corr, 2)} "
                     f"| {share(A.spike_overlap(results[a].events, results[b].events))} "
                     f"| {share(A.spike_overlap(results[b].events, results[a].events))} |")
        L.append("")

    L += ["## Caveats", "",
          "- 16 companies chosen because they are famous today (survivorship bias): good past returns are baked in.",
          "- No trading costs. Spike trades and weekly rebalancing both cost money in reality.",
          "- Testing several sources and thresholds and keeping the best is itself a way to find luck. "
          "Decide the test before looking, or confirm on data you have not used (Week 4).",
          ""]
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L))
    print("\n".join(L))
    print(f"\nWrote {out}")


if __name__ == "__main__":
    main()
